    const roiModTitle = document.querySelector('.comp-card.modern h3');
    const roiModLis = document.querySelectorAll('.comp-card.modern .comp-points li');
    if (roiModBadge) roiModBadge.textContent = dict.roi_modern_badge;
    if (roiModTitle) roiModTitle.textContent = dict.roi_modern_title;
